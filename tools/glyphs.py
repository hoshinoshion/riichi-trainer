"""Writes js/glyphs.js: the characters on the tile faces as SVG path data, so every device draws the same tiles
with no font download.

    pip install fonttools brotli
    curl -o /tmp/tiles.woff2 "<woff2 url from the CSS below>"
    python3 tools/glyphs.py /tmp/tiles.woff2

The font is Shippori Mincho B1 ExtraBold (SIL Open Font License 1.1). Google Fonts serves a subset holding just
these characters from
https://fonts.googleapis.com/css2?family=Shippori+Mincho+B1:wght@800&text=一二三四五六七八九萬東南西北發中
"""
import sys
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

CHARS = '一二三四五六七八九萬東南西北發中'
font = TTFont(sys.argv[1])
cmap, gs = font.getBestCmap(), font.getGlyphSet()
upm = font['head'].unitsPerEm
asc = font['hhea'].ascent
out = {}
for ch in CHARS:
    pen = SVGPathPen(gs, ntos=lambda v: ('%d' % round(v)))
    # Flip y so the paths sit in a 0..upm box with y pointing down, like the SVG viewBox.
    gs[cmap[ord(ch)]].draw(TransformPen(pen, (1, 0, 0, -1, 0, asc - (asc - upm * 0.88))))
    out[ch] = pen.getCommands()
lines = ['// Generated by tools/glyphs.py from Shippori Mincho B1 ExtraBold (SIL Open Font License 1.1); do not edit.',
         '// The tile-face characters as SVG path data in a %d-unit em box (viewBox="0 0 %d %d").' % (upm, upm, upm),
         'const GLYPH_EM = %d;' % upm, 'const GLYPHS = {']
lines += ["  '%s': '%s'," % (ch, d) for ch, d in out.items()]
lines[-1] = lines[-1].rstrip(',')
lines.append('};')
open('js/glyphs.js', 'w').write('\n'.join(lines) + '\n')
print('wrote js/glyphs.js', sum(len(d) for d in out.values()), 'bytes of path data')
