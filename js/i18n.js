const LANG_NAMES={ja:'日本語',en:'English','zh-CN':'简体中文','zh-TW':'繁體中文'};
let LANG='ja';
// First browser language we support wins; Chinese variants split into Traditional (TW, HK, MO, Hant) and Simplified.
// Anything else, or no browser language at all, falls back to Japanese.
function detectLang(){
  const list=(typeof navigator!=='undefined'&&navigator&&(navigator.languages&&navigator.languages.length?navigator.languages:[navigator.language]))||[];
  for(const raw of list){
    const l=String(raw||'').toLowerCase();
    if(l.startsWith('zh'))return /hant|tw|hk|mo/.test(l)?'zh-TW':'zh-CN';
    if(l.startsWith('ja'))return 'ja';
    if(l.startsWith('en'))return 'en';
  }
  return 'ja';
}
function setLang(pref){LANG=STR[pref]?pref:detectLang();return LANG;}
// Plain keys, or "group.item" for an entry inside an object (e.g. lv.easy).
function raw(lang,key){
  const o=STR[lang];if(key in o)return o[key];
  const i=key.indexOf('.');if(i>0){const g=o[key.slice(0,i)];if(g&&typeof g==='object'&&key.slice(i+1) in g)return g[key.slice(i+1)];}
}
function t(key,v){
  let d=raw(LANG,key);if(d===undefined)d=raw('zh-CN',key);
  if(typeof d==='function')return d(v||{});
  if(d==null)return key;
  return v?d.replace(/\{(\w+)\}/g,(m,k)=>v[k]!=null?v[k]:m):d;
}
