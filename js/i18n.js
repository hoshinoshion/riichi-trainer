// ===================== i18n =====================
// UI languages: Japanese, English, Simplified Chinese, Traditional Chinese.
// t(key, vars) looks a key up in the current language (falling back to Simplified Chinese); an entry is either a
// string with {name} placeholders or a function of vars. The engine keeps returning its Simplified Chinese yaku
// and limit names; YN() / LBL() translate them for display. No DOM access here, so Node tests can load this file.
const LANG_NAMES = { ja: '日本語', en: 'English', 'zh-CN': '简体中文', 'zh-TW': '繁體中文' };
let LANG = 'ja';
// First browser language we support wins; Chinese variants split into Traditional (TW, HK, MO, Hant) and Simplified.
// Anything else, or no browser language at all, falls back to Japanese.
function detectLang() {
  const list =
    (typeof navigator !== 'undefined' &&
      navigator &&
      (navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language])) ||
    [];
  for (const raw of list) {
    const l = String(raw || '').toLowerCase();
    if (l.startsWith('zh')) return /hant|tw|hk|mo/.test(l) ? 'zh-TW' : 'zh-CN';
    if (l.startsWith('ja')) return 'ja';
    if (l.startsWith('en')) return 'en';
  }
  return 'ja';
}
function setLang(pref) {
  LANG = STR[pref] ? pref : detectLang();
  return LANG;
}
// Plain keys, or "group.item" for an entry inside an object (e.g. lv.easy).
function raw(lang, key) {
  const o = STR[lang];
  if (key in o) return o[key];
  const i = key.indexOf('.');
  if (i > 0) {
    const g = o[key.slice(0, i)];
    if (g && typeof g === 'object' && key.slice(i + 1) in g) return g[key.slice(i + 1)];
  }
}
function t(key, v) {
  let d = raw(LANG, key);
  if (d === undefined) d = raw('zh-CN', key);
  if (typeof d === 'function') return d(v || {});
  if (d == null) return key;
  return v ? d.replace(/\{(\w+)\}/g, (m, k) => (v[k] != null ? v[k] : m)) : d;
}
const L = k => (k in STR[LANG] ? STR[LANG] : STR['zh-CN'])[k]; // raw entry (arrays, maps, functions)
const P = i => L('players')[i]; // player name by seat index (0 = you)
const TN = x => L('tile')(x); // tile name by tile type 0–33
const W4 = i => L('winds')[i]; // wind (0 east … 3 north), short form
const SH = s => L('sh')(s); // shanten as text
const YN = n => L('yaku')[n] || n; // engine yaku name → display name
const LBL = l => {
  if (!l) return '';
  const m = /^(\d+)倍役满$/.exec(l);
  return m ? t('multiYakuman', { n: m[1] }) : L('limits')[l] || l;
};

